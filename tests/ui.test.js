import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
test('UI renders initial world, advances, intervenes, compares and resets',()=>{
 const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
 const elements=new Map([...html.matchAll(/id="([^"]+)"/g)].map(m=>['#'+m[1],{value:m[1]==='seed'?'DRIFT-2026':m[1]==='event-filter'?'all':'',innerHTML:'',textContent:'',dataset:{},classList:{toggle(){}}}]));
 const steps=[1,10,50,100].map(n=>({dataset:{years:String(n)}}));
 const tabs=['words','grammar','baseline'].map(t=>({dataset:{tab:t},classList:{toggle(){}}}));
 const ctx=vm.createContext({structuredClone,console,setInterval(){return 1},clearInterval(){},setTimeout,document:{querySelector:s=>{assert.ok(elements.has(s),`missing DOM ${s}`);return elements.get(s);},querySelectorAll:s=>s==='[data-years]'?steps:s==='[data-tab]'?tabs:s==='[data-years],#play'?[...steps,elements.get('#play')]:[],createElement(){return{click(){}}}},Blob,URL});
 for(const file of ['data.js','phonology.js','lexicon.js','grammar.js','pressures.js','simulation.js','app.js'])vm.runInContext(readFileSync(new URL('../'+file,import.meta.url),'utf8'),ctx,{filename:file});
 assert.equal(elements.get('#year').textContent,'000');
 assert.match(elements.get('#comparison').innerHTML,/みず/);
 assert.match(elements.get('#pressures').innerHTML,/発音省力化圧力/);
 assert.match(elements.get('#pressures').innerHTML,/明瞭性維持圧力/);
 assert.match(elements.get('#pressures').innerHTML,/文法的曖昧性/);
 assert.match(elements.get('#pressures').innerHTML,/標準化圧力/);
 assert.match(elements.get('#pressures').innerHTML,/接触圧/);
 assert.match(elements.get('#pressure-evidence').textContent,/同音衝突/);
 assert.match(elements.get('#word-trace').innerHTML,/共存する語形/);
 elements.get('#trace-word').value='80';elements.get('#trace-word').onchange();
 assert.match(elements.get('#word-trace').innerHTML,/頭/);
 assert.match(elements.get('#sentences').innerHTML,/ORIGIN \/ 初期日本語/);
 assert.equal((elements.get('#sentences').innerHTML.match(/sentence-card/g)||[]).length,4);
 assert.match(elements.get('#sentence-year').textContent,/0年後/);
 vm.runInContext(`
 const sample=structuredClone(sim.regions[0]);
 sample.words[40].phonemes=D.tokenize('sagana');
 sample.grammar={...sample.grammar,order:'SVO',particle:'',object:''};
 globalThis.sampleSentence=sentence(sample);
 sample.words[40].active=false;
 globalThis.lostSentence=sentence(sample);
 `,ctx);
 const plain=ctx.sampleSentence.replace(/<[^>]*>/g,'');
 assert.equal(plain,'わたし　みる　さがな。');
 assert.match(ctx.sampleSentence,/class="changed"/);
 assert.match(ctx.lostSentence,/魚の語が消失/);
 elements.get('#policies').onclick({target:{closest:()=>({dataset:{policy:'isolate'}})}});
 steps[3].onclick();assert.equal(elements.get('#year').textContent,'100');
 assert.equal(elements.get('#sentence-year').textContent,'100年後');
 tabs[1].onclick();assert.match(elements.get('#comparison').innerHTML,/主語標識/);
 assert.match(elements.get('#comparison').innerHTML,/音韻体系：初期/);
 assert.match(elements.get('#comparison').innerHTML,/話者集団と接触/);
 assert.match(elements.get('#comparison').innerHTML,/使用から生まれる文法/);
 tabs[2].onclick();assert.match(elements.get('#comparison').innerHTML,/同じシード/);
 assert.match(elements.get('#comparison').innerHTML,/圧力の比較/);
 for(let i=0;i<4;i++)steps[3].onclick();assert.equal(elements.get('#year').textContent,'500');assert.equal(elements.get('#play').disabled,true);
 assert.ok(!elements.get('#events').innerHTML.includes('undefined'));
 assert.match(elements.get('#cascades').innerHTML,/誘発|圧力への応答/);
 elements.get('#regions').onclick({target:{closest:()=>({dataset:{region:'2'}})}});
 assert.equal(elements.get('#pressure-region').textContent,'沿岸 / 500年');
 elements.get('#trace-region').value='2';elements.get('#trace-region').onchange();
 assert.match(elements.get('#word-trace').innerHTML,/沿岸/);
 elements.get('#comparison').onclick({target:{closest:s=>s==='[data-word-id]'?{dataset:{wordId:'83'}}:{dataset:{traceRegion:'1'}}}});
 assert.equal(elements.get('#trace-word').value,'83');
 assert.match(elements.get('#word-trace').innerHTML,/新聞/);
 vm.runInContext(`
 sim.regions[1].neologisms.push({id:999,meaning:'試験複合語',phonemes:['k','o','m','e'],basePhonemes:['k','o','m','e'],category:'食物',variants:[{phonemes:['k','o','m','e'],share:1,source:'複合語',path:[]}],senses:[{meaning:'試験複合語',share:1}],history:[]});
 `,ctx);
 elements.get('#trace-word').value='999';elements.get('#trace-word').onchange();
 assert.match(elements.get('#word-trace').innerHTML,/試験複合語/);
 elements.get('#reset').onclick();assert.equal(elements.get('#year').textContent,'000');
 assert.equal(elements.get('#sentence-year').textContent,'0年後');
});
